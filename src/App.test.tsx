// @vitest-environment jsdom
import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { render, screen } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
import App from './App'

describe('space traffic coordination office', () => {
  it('loads coordination cases from the Java API', async () => {
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue({
      ok: true,
      json: async () => [{ id: 1, title: 'Low Earth orbit conjunction review', owner: 'European Space Traffic Team', status: 'Review', priority: 'High' }],
    }))
    const client = new QueryClient({ defaultOptions: { queries: { retry: false } } })
    render(<QueryClientProvider client={client}><App /></QueryClientProvider>)
    expect(await screen.findByText('Low Earth orbit conjunction review')).toBeTruthy()
    expect(screen.getByRole('heading', { name: 'Space Traffic Coordination Office' })).toBeTruthy()
  })
})
